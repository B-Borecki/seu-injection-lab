#include <stdint.h>

#define UART0_BASE 0x4000C000u
#define UARTDR     (*(volatile uint32_t *)(UART0_BASE + 0x000u))
#define UARTFR     (*(volatile uint32_t *)(UART0_BASE + 0x018u))

void *memcpy(void *dest, const void *src, unsigned int n) {
  uint8_t *d = (uint8_t *)dest;
  const uint8_t *s = (const uint8_t *)src;

  for (unsigned int i = 0; i < n; i++) {
    d[i] = s[i];
  }
  return dest;
}

void *memset(void *dest, int val, unsigned int n) {
  uint8_t *d = (uint8_t *)dest;

  for (unsigned int i = 0; i < n; i++) {
    d[i] = (uint8_t)val;
  }
  return dest;
}
// UART
void uart_putc(char c) {
  while (UARTFR & (1u << 5)) {}
  UARTDR = (uint32_t)c;
}

void uart_puts(const char *s) {
  while (*s) uart_putc(*s++);
}

void uart_puthex_u32(uint32_t v) {
  static const char *HEX = "0123456789ABCDEF";
  for (int i = 7; i >= 0; --i) {
    uart_putc(HEX[(v >> (i * 4)) & 0xFu]);
  }
}

void uart_puthex_i32(int32_t v) {
  uart_puthex_u32((uint32_t)v);
}

uint32_t u32_abs_i32(int32_t x) {
  uint32_t ux = (uint32_t)x;
  return (x < 0) ? (uint32_t)(~ux + 1u) : ux;
}

void uart_putdec_u32(uint32_t v) {
    if (v == 0) {
        uart_putc('0');
        return;
    }
    
    char buffer[10];
    int i = 0;
    
    while (v > 0) {
        buffer[i++] = '0' + (v % 10);
        v /= 10;
    }
    
    // Wyświetl od tyłu
    while (i > 0) {
        uart_putc(buffer[--i]);
    }
}

void uart_putdec_i32(int32_t v) {
    if (v < 0) {
        uart_putc('-');
        v = -v;
    }
    uart_putdec_u32((uint32_t)v);
}

void uart_puthex_u64(uint64_t v) {
  static const char *HEX = "0123456789ABCDEF";
  for (int i = 7; i >= 0; --i) {
    uart_putc(HEX[(v >> (i * 4 + 32)) & 0xFu]);
  }
  
  for (int i = 7; i >= 0; --i) {
    uart_putc(HEX[(v >> (i * 4)) & 0xFu]);
  }
}

